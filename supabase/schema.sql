-- LinkBloom database schema (Supabase / PostgreSQL)
-- Reconstructed from the live project. Documentation of the current state,
-- not a migration. Run on a fresh Supabase project to recreate the setup.

-- Tables

create table public.profiles (
  id bigint generated by default as identity,
  user_id uuid not null,
  username text not null,
  display_name text,
  description text,
  theme text not null default 'bloom',
  font text not null default 'elegant',
  button_style text not null default 'filled',
  public boolean not null default false,
  created_at timestamptz not null default now(),
  constraint profiles_pkey primary key (id),
  constraint profiles_user_id_key unique (user_id),
  constraint profiles_username_key unique (username),
  constraint profiles_user_id_fkey foreign key (user_id)
    references auth.users (id) on delete cascade,
  constraint profiles_username_format check (username ~ '^[a-z0-9]{3,20}$')
);

create table public.links (
  id bigint generated by default as identity,
  user_id uuid not null,
  title text not null,
  url text not null,
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  constraint links_pkey primary key (id),
  constraint links_user_id_fkey foreign key (user_id)
    references auth.users (id) on delete cascade
);

create table public.stats (
  id bigint generated by default as identity,
  user_id uuid not null,
  views double precision not null default 0,
  clicks double precision not null default 0,
  views_7_days_ago bigint not null default 0,
  clicks_7_days_ago bigint not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint statss_pkey primary key (id),
  constraint stats_user_id_key unique (user_id),
  constraint stats_user_id_fkey foreign key (user_id)
    references auth.users (id) on delete cascade,
  constraint stats_views_check check (views >= 0),
  constraint stats_clicks_check check (clicks >= 0),
  constraint stats_views_7_days_ago_check check (views_7_days_ago >= 0),
  constraint stats_clicks_7_days_ago_check check (clicks_7_days_ago >= 0)
);

-- Row Level Security

alter table public.profiles enable row level security;
alter table public.links enable row level security;
alter table public.stats enable row level security;

-- links: owner sees all own links, others only enabled links of public profiles.
-- Writes are owner-only.
create policy "Read own or enabled links of public profiles" on public.links
  for select to public
  using (
    (select auth.uid()) = user_id
    or (
      enabled = true
      and exists (
        select 1 from public.profiles p
        where p.user_id = links.user_id and p.public = true
      )
    )
  );
create policy "Enable insert for users based on user_id" on public.links
  for insert to public with check ((select auth.uid()) = user_id);
create policy "Enable update for users based on user_id" on public.links
  for update to public
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);
create policy "Enable delete for users based on user_id" on public.links
  for delete to public using ((select auth.uid()) = user_id);

-- profiles: readable only if public (or own profile), owner-only update.
-- No insert/delete policy: rows are created by the handle_new_user trigger
-- and removed via ON DELETE CASCADE when the auth user is deleted.
create policy "Read public or own profile" on public.profiles
  for select to public
  using (public = true or (select auth.uid()) = user_id);
create policy "Enable update for users based on user_id" on public.profiles
  for update to public using ((select auth.uid()) = user_id);

-- stats: owner-only. No insert policy: created by the handle_new_user trigger.
create policy "Enable read access for all users" on public.stats
  for select to public using ((select auth.uid()) = user_id);
create policy "Enable update for users based on user_id" on public.stats
  for update to public
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);
create policy "Enable delete for users based on user_id" on public.stats
  for delete to public using ((select auth.uid()) = user_id);

-- Functions

-- Creates profile and stats row when a user signs up.
create function public.handle_new_user()
returns trigger
language plpgsql
security definer
as $$
begin
  insert into public.profiles (user_id, username, display_name)
  values (
    new.id,
    new.raw_user_meta_data ->> 'username',
    new.raw_user_meta_data ->> 'display_name'
  );

  insert into public.stats (user_id, views, views_7_days_ago, clicks, clicks_7_days_ago)
  values (new.id, 0, 0, 0, 0);

  return new;
end;
$$;

-- Keeps profiles in sync when username/display_name change in auth metadata.
create function public.handle_user_update()
returns trigger
language plpgsql
security definer
as $$
begin
  update public.profiles
  set
    username = new.raw_user_meta_data ->> 'username',
    display_name = new.raw_user_meta_data ->> 'display_name'
  where user_id = new.id;

  return new;
end;
$$;

-- Checks whether an email belongs to another user. Server-side only (service role).
create function public.check_email_exists(email_to_check text, current_user_id uuid)
returns boolean
language plpgsql
security definer
as $$
begin
  return exists (
    select 1 from auth.users
    where lower(email) = lower(email_to_check)
      and id != current_user_id
  );
end;
$$;

-- Does nothing, only keeps the database active.
create function public.keepalive()
returns void
language plpgsql
as $$
begin
  null;
end;
$$;

-- Triggers on auth.users

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

create trigger on_auth_user_updated
  after update on auth.users
  for each row
  when (
    (old.raw_user_meta_data ->> 'username') is distinct from (new.raw_user_meta_data ->> 'username')
    or (old.raw_user_meta_data ->> 'display_name') is distinct from (new.raw_user_meta_data ->> 'display_name')
  )
  execute function public.handle_user_update();

-- Function grants
-- Without these, anon could call check_email_exists via RPC and enumerate emails.

revoke execute on function public.check_email_exists(text, uuid) from public, anon, authenticated;
grant execute on function public.check_email_exists(text, uuid) to service_role;

revoke execute on function public.handle_new_user() from public, anon, authenticated;
revoke execute on function public.handle_user_update() from public, anon, authenticated;